    "_write_shape_hold",
    "_write_peak_hold",
    "_write_cliff_hold",
    "_write_stack_hold",
    "_write_oedge",
    "_write_nvanna",
    "_write_spd_hold",
    "apply_rs_hysteresis",
    "qr_settings",
    "qr_apply",
    "dedup_levels",
    "force_minvex_R",
    "force_minvex_S",
    "apply_sw_lock",
    "apply_box_latch",
    "apply_warn_hysteresis",
    "apply_flip_gate_hysteresis",
    "apply_negg_hysteresis",
    "apply_roll_reclaim",
