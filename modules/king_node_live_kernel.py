    global _sv_ud_since, _sv_push_since
    if spot is None or v1d is None or math.isnan(spot) or math.isnan(v1d) or v1d <= 0:
        return "", 0, _sv_corr
    if _sv_open_spot is None:
        _sv_open_spot, _sv_open_v1d = float(spot), float(v1d)
